import jax
import jax.numpy as jnp


@jax.jit
def Sutherland(T):
  mu0 = 1.716e-5
  T0  = 273.2e0
  S   = 111.e0
  mu = mu0 * ((T0 + S) / (T + S)) * (T / T0)**1.5
  return mu


@jax.jit
def calc_Ev(dx, dy, dz, rho, u, v, w, p, Rgas, Cp, Pr, E):
  # rho, u, v, w, p [nz,ny,nx]
  T   = p / (Rgas * rho)
  my1 = Sutherland(0.25e0 * (T[1:-1,:-2,:-1]  + T[1:-1,1:-1,:-1] + T[1:-1,:-2,1:]  + T[1:-1,1:-1,1:]))
  my2 = Sutherland(0.25e0 * (T[1:-1,1:-1,:-1] + T[1:-1,2:,:-1]   + T[1:-1,1:-1,1:] + T[1:-1,2:,1:]))
  mz1 = Sutherland(0.25e0 * (T[:-2,1:-1,:-1]  + T[1:-1,1:-1,:-1] + T[:-2,1:-1,1:]  + T[1:-1,1:-1,1:]))
  mz2 = Sutherland(0.25e0 * (T[1:-1,1:-1,:-1] + T[2:,1:-1,:-1]   + T[1:-1,1:-1,1:] + T[2:,1:-1,1:]))
  mx  = Sutherland(0.5e0  * (T[1:-1,1:-1,:-1] + T[1:-1,1:-1,1:]))
  muy = 0.25e0 * (my1 * (-u[1:-1,:-2,:-1]  + u[1:-1,1:-1,:-1] - u[1:-1,:-2,1:]  + u[1:-1,1:-1,1:]) + \
                  my2 * (-u[1:-1,1:-1,:-1] + u[1:-1,2:,:-1]   - u[1:-1,1:-1,1:] + u[1:-1,2:,1:])) / dy[None,:-1,None]
  mvy = 0.25e0 * (my1 * (-v[1:-1,:-2,:-1]  + v[1:-1,1:-1,:-1] - v[1:-1,:-2,1:]  + v[1:-1,1:-1,1:]) + \
                  my2 * (-v[1:-1,1:-1,:-1] + v[1:-1,2:,:-1]   - v[1:-1,1:-1,1:] + v[1:-1,2:,1:])) / dy[None,:-1,None]
  mwz = 0.25e0 * (mz1 * (-w[:-2,1:-1,:-1]  + w[1:-1,1:-1,:-1] - w[:-2,1:-1,1:]  + w[1:-1,1:-1,1:]) + \
                  mz2 * (-w[1:-1,1:-1,:-1] + w[2:,1:-1,:-1]   - w[1:-1,1:-1,1:] + w[2:,1:-1,1:])) / dz[:-1,None,None]
  muz = 0.25e0 * (mz1 * (-u[:-2,1:-1,:-1]  + u[1:-1,1:-1,:-1] - u[:-2,1:-1,1:]  + u[1:-1,1:-1,1:]) + \
                  mz2 * (-u[1:-1,1:-1,:-1] + u[2:,1:-1,:-1]   - u[1:-1,1:-1,1:] + u[2:,1:-1,1:])) / dz[:-1,None,None]
  mux = mx * (-u[1:-1,1:-1,:-1] + u[1:-1,1:-1,1:]) / dx[None,None,:]
  mvx = mx * (-v[1:-1,1:-1,:-1] + v[1:-1,1:-1,1:]) / dx[None,None,:]
  mwx = mx * (-w[1:-1,1:-1,:-1] + w[1:-1,1:-1,1:]) / dx[None,None,:]
  txx = 2.e0 * (2.e0 * mux - mvy - mwz) / 3.e0
  tyx = mvx + muy
  tzx = mwx + muz
  E = E.at[:,:,:,0].set(E[:,:,:,0])
  E = E.at[:,:,:,1].set(E[:,:,:,1] - txx)
  E = E.at[:,:,:,2].set(E[:,:,:,2] - tyx)
  E = E.at[:,:,:,3].set(E[:,:,:,3] - tzx)
  E = E.at[:,:,:,4].set(E[:,:,:,4] - (0.5e0 * (u[1:-1,1:-1,:-1] + u[1:-1,1:-1,1:]) * txx + \
                                      0.5e0 * (v[1:-1,1:-1,:-1] + v[1:-1,1:-1,1:]) * tyx + \
                                      0.5e0 * (w[1:-1,1:-1,:-1] + w[1:-1,1:-1,1:]) * tzx + \
                                      Cp * mx * (-T[1:-1,1:-1,:-1] + T[1:-1,1:-1,1:]) / (Pr * dx[None,None,:])))
  return E


@jax.jit
def calc_Fv(dx, dy, dz, rho, u, v, w, p, Rgas, Cp, Pr, F):
  T   = p / (Rgas * rho)
  mz1 = Sutherland(0.25e0 * (T[:-2,:-1,1:-1]  + T[1:-1,:-1,1:-1] + T[:-2,1:,1:-1]  + T[1:-1,1:,1:-1]))
  mz2 = Sutherland(0.25e0 * (T[1:-1,:-1,1:-1] + T[2:,:-1,1:-1]   + T[1:-1,1:,1:-1] + T[2:,1:,1:-1]))
  mx1 = Sutherland(0.25e0 * (T[1:-1,:-1,:-2]  + T[1:-1,:-1,1:-1] + T[1:-1,1:,:-2]  + T[1:-1,1:,1:-1]))
  mx2 = Sutherland(0.25e0 * (T[1:-1,:-1,1:-1] + T[1:-1,:-1,2:]   + T[1:-1,1:,1:-1] + T[1:-1,1:,2:]))
  my  = Sutherland(0.5e0  * (T[1:-1,:-1,1:-1] + T[1:-1,1:,1:-1]))
  mvz = 0.25e0 * (mz1 * (-v[:-2,:-1,1:-1]  + v[1:-1,:-1,1:-1] - v[:-2,1:,1:-1]  + v[1:-1,1:,1:-1]) + \
                  mz2 * (-v[1:-1,:-1,1:-1] + v[2:,:-1,1:-1]   - v[1:-1,1:,1:-1] + v[2:,1:,1:-1])) / dz[:-1,None,None]
  mwz = 0.25e0 * (mz1 * (-w[:-2,:-1,1:-1]  + w[1:-1,:-1,1:-1] - w[:-2,1:,1:-1]  + w[1:-1,1:,1:-1]) + \
                  mz2 * (-w[1:-1,:-1,1:-1] + w[2:,:-1,1:-1]   - w[1:-1,1:,1:-1] + w[2:,1:,1:-1])) / dz[:-1,None,None]
  mux = 0.25e0 * (mx1 * (-u[1:-1,:-1,:-2]  + u[1:-1,:-1,1:-1] - u[1:-1,1:,:-2]  + u[1:-1,1:,1:-1]) + \
                  mx2 * (-u[1:-1,:-1,1:-1] + u[1:-1,:-1,2:]   - u[1:-1,1:,1:-1] + u[1:-1,1:,2:])) / dx[None,None,:-1]
  mvx = 0.25e0 * (mx1 * (-v[1:-1,:-1,:-2]  + v[1:-1,:-1,1:-1] - v[1:-1,1:,:-2]  + v[1:-1,1:,1:-1]) + \
                  mx2 * (-v[1:-1,:-1,1:-1] + v[1:-1,:-1,2:]   - v[1:-1,1:,1:-1] + v[1:-1,1:,2:])) / dx[None,None,:-1]
  muy = my * (-u[1:-1,:-1,1:-1] + u[1:-1,1:,1:-1]) / dy[None,:,None]
  mvy = my * (-v[1:-1,:-1,1:-1] + v[1:-1,1:,1:-1]) / dy[None,:,None]
  mwy = my * (-w[1:-1,:-1,1:-1] + w[1:-1,1:,1:-1]) / dy[None,:,None]
  txy = muy + mvx
  tyy = 2.e0 * (2.e0 * mvy - mwz - mux) / 3.e0
  tzy = mwy + mvz
  F = F.at[:,:,:,0].set(F[:,:,:,0])
  F = F.at[:,:,:,1].set(F[:,:,:,1] - txy)
  F = F.at[:,:,:,2].set(F[:,:,:,2] - tyy)
  F = F.at[:,:,:,3].set(F[:,:,:,3] - tzy)
  F = F.at[:,:,:,4].set(F[:,:,:,4] - (0.5e0 * (u[1:-1,:-1,1:-1] + u[1:-1,1:,1:-1]) * txy + \
                                      0.5e0 * (v[1:-1,:-1,1:-1] + v[1:-1,1:,1:-1]) * tyy + \
                                      0.5e0 * (w[1:-1,:-1,1:-1] + w[1:-1,1:,1:-1]) * tzy + \
                                      Cp * my * (-T[1:-1,:-1,1:-1] + T[1:-1,1:,1:-1]) / (Pr * dy[None,:,None])))
  return F


@jax.jit
def calc_Gv(dx, dy, dz, rho, u, v, w, p, Rgas, Cp, Pr, G):
  T   = p / (Rgas * rho)
  mx1 = Sutherland(0.25e0 * (T[:-1,1:-1,:-2]  + T[:-1,1:-1,1:-1] + T[1:,1:-1,:-2]  + T[1:,1:-1,1:-1]))
  mx2 = Sutherland(0.25e0 * (T[:-1,1:-1,1:-1] + T[:-1,1:-1,2:]   + T[1:,1:-1,1:-1] + T[1:,1:-1,2:]))
  my1 = Sutherland(0.25e0 * (T[:-1,:-2,1:-1]  + T[:-1,1:-1,1:-1] + T[1:,:-2,1:-1]  + T[1:,1:-1,1:-1]))
  my2 = Sutherland(0.25e0 * (T[:-1,1:-1,1:-1] + T[:-1,2:,1:-1]   + T[1:,1:-1,1:-1] + T[1:,2:,1:-1]))
  mz  = Sutherland(0.5e0  * (T[:-1,1:-1,1:-1] + T[1:,1:-1,1:-1]))
  mwx = 0.25e0 * (mx1 * (-w[:-1,1:-1,:-2]  + w[:-1,1:-1,1:-1] - w[1:,1:-1,:-2]  + w[1:,1:-1,1:-1]) + \
                  mx2 * (-w[:-1,1:-1,1:-1] + w[:-1,1:-1,2:]   - w[1:,1:-1,1:-1] + w[1:,1:-1,2:])) / dx[None,None,:-1]
  mux = 0.25e0 * (mx1 * (-u[:-1,1:-1,:-2]  + u[:-1,1:-1,1:-1] - u[1:,1:-1,:-2]  + u[1:,1:-1,1:-1]) + \
                  mx2 * (-u[:-1,1:-1,1:-1] + u[:-1,1:-1,2:]   - u[1:,1:-1,1:-1] + u[1:,1:-1,2:])) / dx[None,None,:-1]
  mvy = 0.25e0 * (my1 * (-v[:-1,:-2,1:-1]  + v[:-1,1:-1,1:-1] - v[1:,:-2,1:-1]  + v[1:,1:-1,1:-1]) + \
                  my2 * (-v[:-1,1:-1,1:-1] + v[:-1,2:,1:-1]   - v[1:,1:-1,1:-1] + v[1:,2:,1:-1])) / dy[None,:-1,None]
  mwy = 0.25e0 * (my1 * (-w[:-1,:-2,1:-1]  + w[:-1,1:-1,1:-1] - w[1:,:-2,1:-1]  + w[1:,1:-1,1:-1]) + \
                  my2 * (-w[:-1,1:-1,1:-1] + w[:-1,2:,1:-1]   - w[1:,1:-1,1:-1] + w[1:,2:,1:-1])) / dy[None,:-1,None]
  muz = mz * (-u[:-1,1:-1,1:-1] + u[1:,1:-1,1:-1]) / dz[:,None,None]
  mvz = mz * (-v[:-1,1:-1,1:-1] + v[1:,1:-1,1:-1]) / dz[:,None,None]
  mwz = mz * (-w[:-1,1:-1,1:-1] + w[1:,1:-1,1:-1]) / dz[:,None,None]
  txz = muz + mwx
  tyz = mvz + mwy
  tzz = 2.e0 * (2.e0 * mwz - mux - mvy) / 3.e0
  G = G.at[:,:,:,0].set(G[:,:,:,0])
  G = G.at[:,:,:,1].set(G[:,:,:,1] - txz)
  G = G.at[:,:,:,2].set(G[:,:,:,2] - tyz)
  G = G.at[:,:,:,3].set(G[:,:,:,3] - tzz)
  G = G.at[:,:,:,4].set(G[:,:,:,4] - (0.5e0 * (u[:-1,1:-1,1:-1] + u[1:,1:-1,1:-1]) * txz + \
                                      0.5e0 * (v[:-1,1:-1,1:-1] + v[1:,1:-1,1:-1]) * tyz + \
                                      0.5e0 * (w[:-1,1:-1,1:-1] + w[1:,1:-1,1:-1]) * tzz + \
                                      Cp * mz * (-T[:-1,1:-1,1:-1] + T[1:,1:-1,1:-1]) / (Pr * dz[:,None,None])))
  return G

